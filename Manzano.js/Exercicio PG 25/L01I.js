alert("Recebe um valor e converte ao quadrado. ");

let a = parseFloat(prompt("Digite o valor de A: "));

let b = parseFloat(prompt("Digite o valor de B: "));

let resultadoA = a - b;

alert("Diferença de A e B é: " + resultadoA);

