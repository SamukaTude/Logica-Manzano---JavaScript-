alert("Calcula e apresenta o volume de uma lata de óleo utilizando o valor de π, o raio e a altura da lata. ");

pi = 3,14

raio = parseFloat(prompt("Digite o raio: "));

altura = parseFloat(prompt("Digite a altura: "));

volume = pi * raio * raio * altura

alert("O valor do volume de uma lata de óleo é: " + volume);
